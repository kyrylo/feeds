//! Local owner provisioning and recovery, without an email service.
use crate::{browser, schema};
use sqlx::SqlitePool;
use std::io::Read;

pub fn read_password(mut input: impl Read) -> schema::Result<String> {
    let mut bytes = Vec::new();
    input.by_ref().take(75).read_to_end(&mut bytes)?;
    if bytes.ends_with(b"\n") {
        bytes.pop();
        if bytes.ends_with(b"\r") {
            bytes.pop();
        }
    }
    let password = String::from_utf8(bytes)?;
    if password.chars().count() < 12 || password.len() > 72 {
        return Err("choose a password of at least 12 characters and at most 72 bytes".into());
    }
    Ok(password)
}

pub fn hash_password(password: &str) -> schema::Result<String> {
    Ok(bcrypt::hash(password, 12)?)
}

/// The stored owner always wins. A bootstrap secret never resets a password.
pub async fn bootstrap(
    pool: &SqlitePool,
    digest: Option<&str>,
    email: Option<&str>,
) -> schema::Result<bool> {
    let mut tx = pool.begin_with("BEGIN IMMEDIATE").await?;
    let configured: bool = sqlx::query_scalar("SELECT EXISTS(SELECT 1 FROM accounts)")
        .fetch_one(&mut *tx)
        .await?;
    if configured {
        return Ok(false);
    }
    let Some(digest) = digest else {
        return Ok(false);
    };
    let hash: bcrypt::HashParts = digest
        .parse()
        .map_err(|_| "FEEDS_PASSWORD_HASH must be generated by feeds hash-password")?;
    if !(12..=16).contains(&hash.get_cost()) {
        return Err("FEEDS_PASSWORD_HASH must have a bcrypt cost between 12 and 16".into());
    }
    let email = email.unwrap_or("owner@localhost").trim().to_lowercase();
    if !browser::valid_email(&email) {
        return Err("FEEDS_OWNER_EMAIL must be a valid email address".into());
    }
    let account: i64 = sqlx::query_scalar("INSERT INTO accounts (join_code,created_at,updated_at) VALUES ($1,now(),now()) RETURNING id")
        .bind(browser::join_code()).fetch_one(&mut *tx).await?;
    sqlx::query("INSERT INTO users (account_id,email_address,nickname,password_digest,role,created_at,updated_at) VALUES ($1,$2,'owner',$3,2,now(),now())")
        .bind(account).bind(email).bind(digest).execute(&mut *tx).await?;
    tx.commit().await?;
    Ok(true)
}

pub async fn reset_password(pool: &SqlitePool, digest: &str) -> schema::Result<()> {
    let mut tx = pool.begin_with("BEGIN IMMEDIATE").await?;
    let users: Vec<i64> = sqlx::query_scalar("SELECT id FROM users ORDER BY id LIMIT 2")
        .fetch_all(&mut *tx)
        .await?;
    let [owner] = users.as_slice() else {
        return Err("reset-password requires an existing single-owner database; for imported multi-user installations, use account settings or email recovery".into());
    };
    sqlx::query("UPDATE users SET password_digest=$1,updated_at=now() WHERE id=$2")
        .bind(digest)
        .bind(owner)
        .execute(&mut *tx)
        .await?;
    sqlx::query("DELETE FROM sessions WHERE user_id=$1")
        .bind(owner)
        .execute(&mut *tx)
        .await?;
    tx.commit().await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn password_input_is_bounded_and_keeps_intentional_whitespace() {
        assert_eq!(
            read_password(&b"a long password  \r\n"[..]).unwrap(),
            "a long password  "
        );
        assert!(read_password(&b"too short"[..]).is_err());
        assert!(read_password(&[b'a'; 73][..]).is_err());
        assert!(read_password(&[b'a'; 1_000_000][..]).is_err());
        assert!(read_password("😀😀😀😀😀😀😀😀😀😀😀😀😀😀😀😀😀😀😀".as_bytes()).is_err());
    }
}
